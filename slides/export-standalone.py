#!/usr/bin/env python3
"""Export completed decks as HTML with local styles, scripts, and chart data.

Run from any directory: python3 slides/export-standalone.py
The existing CDN libraries and web fonts still require an internet connection.
"""
from __future__ import annotations

import argparse
import base64
import json
import posixpath
import re
from pathlib import Path
from urllib.parse import urljoin, urlsplit

ROOT = Path(__file__).resolve().parent.parent
DECK = ROOT / 'slides/presentation-01/index.html'
OUTPUT = ROOT / 'courses/deep-learning-aau/topics/01-regression/slides/regression-exercises.html'


def is_remote(url: str) -> bool:
    return bool(urlsplit(url).scheme or url.startswith('//'))


def inline_css(path: Path) -> str:
    def replace_import(match: re.Match) -> str:
        url = match.group(1)
        if is_remote(url):
            return match.group()
        return inline_css((path.parent / url).resolve())

    return re.sub(
        r'@import\s+url\([\'"]([^\'"]+)[\'"]\)\s*;',
        replace_import,
        path.read_text(),
    )


def export(site_url: str) -> str:
    html = DECK.read_text()

    def replace_link(match: re.Match) -> str:
        tag, rel, href = match.group(), match.group(1), match.group(2)
        if is_remote(href):
            return tag
        path = (DECK.parent / href).resolve()
        if rel == 'stylesheet':
            return '<style>\n' + inline_css(path) + '\n</style>'
        if rel == 'icon':
            data = base64.b64encode(path.read_bytes()).decode('ascii')
            return f'<link rel="icon" href="data:image/svg+xml;base64,{data}"/>'
        raise ValueError(f'Unsupported local link: {tag}')

    html = re.sub(r'<link rel="([^"]+)" href="([^"]+)"\s*/>', replace_link, html)
    scripts = []

    def replace_script(match: re.Match) -> str:
        src = match.group(1)
        if is_remote(src):
            scripts.append(f'<script src="{src}"></script>')
        else:
            code = (DECK.parent / src).read_text()
            code = re.sub(r'</script', r'<\/script', code, flags=re.I)
            scripts.append('<script>\n' + code + '\n</script>')
        return ''

    # Blocking scripts at the end of the body retain the source's defer order.
    html = re.sub(r'^[ \t]*<script defer src="([^"]+)"></script>[ \t]*\n?', replace_script, html, flags=re.M)
    data_path = DECK.parent / 'assets/regression-walkthrough.json'
    data = json.dumps(json.loads(data_path.read_text()), separators=(',', ':'), ensure_ascii=False)
    data = data.replace('<', '\\u003c')
    embedded = '<script type="application/json" id="regression-walkthrough-data">' + data + '</script>'
    html = html.replace('</body>', embedded + '\n' + '\n'.join(scripts) + '\n</body>')

    def course_navigation(match: re.Match) -> str:
        href = match.group(1)
        if href.startswith('#') or is_remote(href):
            return match.group()
        target = urlsplit(urljoin(DECK.relative_to(ROOT).as_posix(), href))
        relative = posixpath.relpath(target.path, OUTPUT.parent.relative_to(ROOT).as_posix())
        if target.path.endswith('/'):
            relative += '/'
        return f'href="{relative}"'

    html = re.sub(r'href="([^"]+)"', course_navigation, html)
    # Hosted navigation stays relative, while downloaded files return to the site.
    published_url = json.dumps(urljoin(site_url, OUTPUT.relative_to(ROOT).as_posix()))
    file_navigation = r'''<script>
if (location.protocol === 'file:') {
  document.querySelectorAll('a[href]').forEach((link) => {
    const href = link.getAttribute('href');
    if (!href.startsWith('#') && !/^(?:[a-z]+:|\/\/)/i.test(href)) {
      link.href = new URL(href, PUBLISHED_URL).href;
    }
  });
}
</script>'''.replace('PUBLISHED_URL', published_url)
    html = html.replace('</body>', file_navigation + '\n</body>')
    return html.replace('<head>', '<head>\n  <!-- Generated by slides/export-standalone.py; edit slides/presentation-01/ instead. -->', 1)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--site-url', default='https://archie-c.github.io/', help='Website base URL for course navigation in downloaded files.')
    parser.add_argument('--check', action='store_true', help='Fail if the committed export needs to be regenerated.')
    args = parser.parse_args()
    site_url = args.site_url.rstrip('/') + '/'
    if urlsplit(site_url).scheme not in ('http', 'https') or not urlsplit(site_url).netloc:
        parser.error('--site-url must be an absolute HTTP or HTTPS URL')
    html = export(site_url)
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != html:
            parser.exit(1, 'Standalone slides are out of date; run python3 slides/export-standalone.py\n')
        print('Standalone slides are up to date.')
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(html)
        print(f'Exported {OUTPUT.relative_to(ROOT)} ({OUTPUT.stat().st_size:,} bytes).')


if __name__ == '__main__':
    main()
