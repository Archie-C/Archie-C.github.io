// Copy pinned browser distributions; no bundler or npm install is needed to serve the site.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..', '..');
const out = path.join(root, 'a-level/assets');
fs.mkdirSync(path.join(out, 'vendor'), {recursive:true});
const packages = {
  '@supabase/supabase-js': ['dist/umd/supabase.js'],
  marked: ['lib/marked.umd.js'],
  dompurify: ['dist/purify.min.js'],
  katex: ['dist/katex.min.js','dist/katex.min.css','dist/contrib/auto-render.min.js','dist/fonts']
};
for (const [name, files] of Object.entries(packages)) {
  const source = path.join(__dirname, 'node_modules', name);
  for (const file of files) fs.cpSync(path.join(source,file), path.join(out,'vendor',path.basename(file)), {recursive:true});
  const licence = ['LICENSE','LICENSE.txt','LICENSE.md'].find(file => fs.existsSync(path.join(source,file)));
  if (licence) fs.copyFileSync(path.join(source,licence),path.join(out,'vendor',name.replaceAll('/','-')+'-LICENSE.txt'));
}
fs.copyFileSync(path.join(root,'design_system/colors_and_type.css'),path.join(out,'colors_and_type.css'));
fs.copyFileSync(path.join(root,'design_system/assets/favicon.svg'),path.join(out,'favicon.svg'));
fs.copyFileSync(path.join(__dirname,'node_modules/@supabase/auth-js/LICENSE'),path.join(out,'vendor/supabase-LICENSE.txt'));
fs.copyFileSync(path.join(__dirname,'node_modules/tslib/LICENSE.txt'),path.join(out,'vendor/tslib-LICENSE.txt'));
fs.copyFileSync(path.join(__dirname,'node_modules/ws/LICENSE'),path.join(out,'vendor/ws-LICENSE.txt'));
const notices=['# Vendored browser dependencies','', 'Generated by `a-level/tests/vendor.cjs`. See adjacent licence files.',''];
for(const name of [...Object.keys(packages),'@supabase/auth-js','@supabase/functions-js','@supabase/postgrest-js','@supabase/realtime-js','@supabase/storage-js','tslib','ws']) {
  const pkg=JSON.parse(fs.readFileSync(path.join(__dirname,'node_modules',name,'package.json'),'utf8'));
  notices.push(`- ${name} ${pkg.version} — ${pkg.license}. Source: ${typeof pkg.repository==='string'?pkg.repository:pkg.repository?.url||pkg.homepage||'https://www.npmjs.com/package/'+name}`);
}
fs.writeFileSync(path.join(out,'vendor/NOTICE.md'),notices.join('\n')+'\n');
console.log('Copied pinned vendor assets and the current site design tokens.');
