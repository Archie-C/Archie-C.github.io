"""Rebuild deterministic catalogue JSON and SQL from the two board-specific CSVs."""
import csv
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / 'supabase' / 'revision'


def slug(text):
    return re.sub(r'[^a-z0-9]+', '-', text.lower()).strip('-')


def build():
    data = {'subjects': [], 'specifications': [], 'books': [], 'chapters': [], 'subtopics': [], 'papers': [], 'paper_chapters': []}
    seen_books, seen_chapters = set(), set()
    for subject, folder, code in [('maths', 'mathematics', '9ma0'), ('further-maths', 'further_mathematics', '9fm0')]:
        spec = 'edexcel-' + code
        data['subjects'].append(dict(id=subject, name='Mathematics' if subject == 'maths' else 'Further Mathematics', board='Edexcel'))
        data['specifications'].append(dict(id=spec, subject_id=subject, code=code.upper(), title='A-level ' + ('Mathematics' if subject == 'maths' else 'Further Mathematics'),
            source_url='https://qualifications.pearson.com/en/qualifications/edexcel-a-levels/mathematics-2017.html'))
        with (ROOT / 'a-level' / folder / 'edexcel' / 'topics.csv').open(encoding='utf-8-sig', newline='') as source:
            for row in csv.DictReader(source):
                book = subject + '-' + slug(row['Book'])
                chapter = book + '-ch' + row['Chapter_Number'].zfill(2)
                required = subject == 'maths' or row['Book'].startswith('Core Pure')
                if book not in seen_books:
                    seen_books.add(book)
                    family = None if required else re.sub(r' [12]$', '', row['Book'])
                    data['books'].append(dict(id=book, specification_id=spec, title=row['Book'], required=required,
                        option_family=family, option_level=None if required else int(row['Book'][-1]), sort_order=len(seen_books)))
                if chapter not in seen_chapters:
                    seen_chapters.add(chapter)
                    data['chapters'].append(dict(id=chapter, book_id=book, number=int(row['Chapter_Number']), title=row['Topic']))
                data['subtopics'].append(dict(id=book+'-s'+row['Subtopic_Number'].replace('.', '-'), chapter_id=chapter,
                    number=row['Subtopic_Number'], title=row['Subtopic'], page_start=int(row['Page_Start']), page_count=int(row['Page_Count']),
                    length_rating=int(row['Length_Rating']), difficulty_rating=int(row['Difficulty_Rating']), strand=row['Subject']))
    # Textbook volumes and examination papers are separate entities.
    for suffix, title in [('01','Pure mathematics 1'), ('02','Pure mathematics 2'), ('03','Statistics and mechanics')]:
        pid = '9ma0-' + suffix
        data['papers'].append(dict(id=pid, specification_id='edexcel-9ma0', title=title, option_book_id=None))
        for ch in data['chapters']:
            if ch['book_id'].startswith('maths-') and (('pure-mathematics' in ch['book_id']) == (suffix != '03')):
                data['paper_chapters'].append(dict(paper_id=pid, chapter_id=ch['id']))
    for suffix in ['01', '02']:
        pid = '9fm0-' + suffix
        data['papers'].append(dict(id=pid, specification_id='edexcel-9fm0', title='Core pure mathematics '+suffix[-1], option_book_id=None))
        for ch in data['chapters']:
            if ch['book_id'].startswith('further-maths-core-pure'):
                data['paper_chapters'].append(dict(paper_id=pid, chapter_id=ch['id']))
    # Use content-option IDs; an optional subject 1 can occupy either optional paper slot.
    for book in data['books']:
        if book['specification_id']=='edexcel-9fm0' and not book['required']:
            pid = '9fm0-option-' + slug(book['title'])
            data['papers'].append(dict(id=pid, specification_id='edexcel-9fm0', title=book['title'], option_book_id=book['id']))
            data['paper_chapters'].extend(dict(paper_id=pid, chapter_id=c['id']) for c in data['chapters'] if c['book_id']==book['id'])
    return data


def main():
    data = build()
    OUTPUT.mkdir(parents=True, exist_ok=True)
    # JSON is for fixtures and authoring IDs; student catalogue comes from Supabase.
    (ROOT / 'a-level' / 'catalogue.json').write_text(json.dumps(data, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
    sql = ['-- Generated by a-level/tools/generate_catalogue.py. No exam dates are seeded.', 'begin;']
    for table, rows in data.items():
        columns = list(rows[0])
        sql.append('insert into public.revision_' + table + ' (' + ','.join(columns) + ') values')
        def literal(v):
            if v is None: return 'null'
            if isinstance(v, bool): return str(v).lower()
            if isinstance(v, int): return str(v)
            return "'"+v.replace("'", "''")+"'"
        sql.append(',\n'.join('('+','.join(literal(row[c]) for c in columns)+')' for row in rows))
        keys = ['paper_id', 'chapter_id'] if table=='paper_chapters' else ['id']
        updates = [c+'=excluded.'+c for c in columns if c not in keys]
        sql.append('on conflict ('+','.join(keys)+') do '+('update set '+','.join(updates) if updates else 'nothing')+';')
    sql.append('commit;')
    (OUTPUT / '04-catalogue.sql').write_text('\n'.join(sql)+'\n', encoding='utf-8')
    print({key: len(value) for key, value in data.items()})


if __name__ == '__main__':
    main()
